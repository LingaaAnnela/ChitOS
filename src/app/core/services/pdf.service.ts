import { Injectable } from '@angular/core';
import jsPDF from 'jspdf';

export interface GroupReportParams {
  groupName: string;
  strategy: string;
  endDate: string;
  totalCollected: number;
  totalDisbursed: number;
  durationMonths: number;
  memberCount: number;
  payouts: Array<{
    memberName: string;
    cycleNumber: number;
    amount: number;
    date: string;
  }>;
}

@Injectable({ providedIn: 'root' })
export class PdfService {

  downloadGroupReport(params: GroupReportParams): void {
    const {
      groupName, strategy, endDate,
      totalCollected, totalDisbursed, durationMonths, memberCount, payouts,
    } = params;

    const fmt = (n: number) => '₹' + new Intl.NumberFormat('en-IN').format(n);
    const doc = new jsPDF({ orientation: 'portrait', unit: 'mm', format: 'a4' });
    let y = 20;
    const lh = (n = 7) => { y += n; };

    // Title
    doc.setFontSize(20);
    doc.setFont('helvetica', 'bold');
    doc.setTextColor(26, 26, 26);
    doc.text(groupName, 15, y);

    lh(7);
    doc.setFontSize(10);
    doc.setFont('helvetica', 'normal');
    doc.setTextColor(107, 107, 107);
    doc.text(`Final Group Report · ${strategy} · Completed ${endDate}`, 15, y);

    lh(12);
    // Divider
    doc.setDrawColor(230, 230, 225);
    doc.setLineWidth(0.3);
    doc.line(15, y, 195, y);

    lh(10);
    doc.setFontSize(12);
    doc.setFont('helvetica', 'bold');
    doc.setTextColor(26, 26, 26);
    doc.text('Summary', 15, y);

    lh(8);
    doc.setFontSize(10);
    doc.setFont('helvetica', 'normal');

    const summaryRows: [string, string][] = [
      ['Total collected',  fmt(totalCollected)],
      ['Total disbursed',  fmt(totalDisbursed)],
      ['Duration',         `${durationMonths} months`],
      ['Members',          `${memberCount} members`],
    ];
    for (const [label, value] of summaryRows) {
      doc.setTextColor(107, 107, 107);
      doc.text(label, 15, y);
      doc.setTextColor(26, 26, 26);
      doc.setFont('helvetica', 'bold');
      doc.text(value, 80, y);
      doc.setFont('helvetica', 'normal');
      lh(6);
    }

    lh(8);
    doc.setDrawColor(230, 230, 225);
    doc.line(15, y, 195, y);

    lh(10);
    doc.setFontSize(12);
    doc.setFont('helvetica', 'bold');
    doc.setTextColor(26, 26, 26);
    doc.text('Member Payouts', 15, y);

    lh(8);
    // Table header
    doc.setFontSize(9);
    doc.setFont('helvetica', 'bold');
    doc.setTextColor(168, 163, 154);
    doc.text('CYCLE', 15, y);
    doc.text('MEMBER', 35, y);
    doc.text('AMOUNT RECEIVED', 110, y);
    doc.text('DATE', 160, y);

    lh(4);
    doc.setDrawColor(200, 200, 195);
    doc.line(15, y, 195, y);
    lh(6);

    doc.setFontSize(10);
    doc.setFont('helvetica', 'normal');
    for (const p of payouts) {
      doc.setTextColor(107, 107, 107);
      doc.text(`C${p.cycleNumber}`, 15, y);
      doc.setTextColor(26, 26, 26);
      doc.text(p.memberName, 35, y);
      doc.setTextColor(22, 163, 74);
      doc.text(fmt(p.amount), 110, y);
      doc.setTextColor(107, 107, 107);
      doc.text(p.date, 160, y);
      lh(7);
    }

    lh(6);
    doc.setFontSize(8);
    doc.setTextColor(168, 163, 154);
    doc.text('Generated by ChitOS · chitos.app', 15, y);

    const filename = groupName.replace(/[^a-z0-9]/gi, '-').toLowerCase() + '-report.pdf';
    doc.save(filename);
  }
}
